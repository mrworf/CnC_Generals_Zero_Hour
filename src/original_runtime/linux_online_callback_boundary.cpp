#include <stdexcept>

namespace {
[[noreturn]] void unsupported_online_callback(const char *name)
{
	throw std::runtime_error(std::string("unsupported online callback: ") + name);
}
}

#define ZH_UNSUPPORTED_WINDOW_CALLBACK(name) \
	WindowMsgHandledType name(GameWindow *, UnsignedInt, WindowMsgData, WindowMsgData) \
	{ \
		unsupported_online_callback(#name); \
	}

#define ZH_UNSUPPORTED_LAYOUT_CALLBACK(name) \
	void name(WindowLayout *, void *) \
	{ \
		unsupported_online_callback(#name); \
	}

